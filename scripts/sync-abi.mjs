// Copies ABI + bytecode from Foundry artifacts into packages/core/src/abi/generated.ts so TypeScript packages
// never import from another package's build output. Run after `forge build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "packages/contracts/out");
const contracts = [
  "AgentAccount",
  "MockUSDC",
  "ReceiptRegistry",
  "SpendLimitEnforcer",
  "TimeWindowEnforcer",
  "AllowedTargetsEnforcer",
];

let ts = `// GENERATED by scripts/sync-abi.mjs from packages/contracts/out. Do not edit.\n`;
for (const name of contracts) {
  const art = JSON.parse(readFileSync(resolve(out, `${name}.sol`, `${name}.json`), "utf8"));
  ts += `\nexport const ${name}Abi = ${JSON.stringify(art.abi)} as const;\n`;
  ts += `export const ${name}Bytecode = ${JSON.stringify(art.bytecode.object)} as const;\n`;
}
const dest = resolve(root, "packages/core/src/abi/generated.ts");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, ts);
console.log(`wrote ${dest}`);
